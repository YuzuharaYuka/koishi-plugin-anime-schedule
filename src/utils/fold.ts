/** 归一化：转简体 → 去括号补充 → 只保留文字与字母数字 */
export function foldTitle(value: string): string {
  const converted = [...(value ?? '')].map((char) => VARIANTS[char] ?? char).join('')
  return converted
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[（(【\[「『][^）)】\]」』]*[）)】\]」』]/g, '')
    .replace(/[^\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}a-z0-9]/gu, '')
}
